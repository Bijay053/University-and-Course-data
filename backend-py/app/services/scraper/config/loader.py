"""Load and merge per-university scraper configuration.

Priority chain (lowest → highest):
  1. Built-in Pydantic defaults (schema.py field defaults)
  2. ``scraper_config/defaults.yaml``            — conservative global defaults
  3. DB ``university.scrape_config.uniPages``    — backwards-compat manual UI config
  4. DB ``university.scrape_config.auto_config`` — auto-generated by site probe (NEW)
  5. ``scraper_config/unis/<slug>.yaml``          — per-university YAML (emergency override)

The loader is intentionally synchronous: it is called once per scrape job
at worker startup, before any async I/O.  Results are NOT cached at the
module level so that config file changes take effect on the next scrape
without requiring a worker restart.  If the startup cost becomes measurable
(unlikely given ~20 YAML files), add an LRU cache keyed on (slug, mtime).

Slug derivation
---------------
The slug is derived from the primary hostname of the university's scrape URL:

  www.acu.edu.au  →  acu
  www.aut.ac.nz   →  aut
  bond.edu.au     →  bond

The per-university YAML file is looked up at ``unis/<slug>.yaml``.  If no
file exists for that slug the loader falls back to a config built from
defaults only (plus the DB scrape_config backwards-compat translation).
"""
from __future__ import annotations

import copy
import logging
import re
from datetime import date
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import yaml

from app.services.scraper.config.schema import UniConfig

log = logging.getLogger(__name__)

_CONFIGS_ROOT = Path(__file__).parent.parent.parent.parent.parent / "scraper_config"
_DEFAULTS_FILE = _CONFIGS_ROOT / "defaults.yaml"
_UNIS_DIR = _CONFIGS_ROOT / "unis"

# Common TLD-style tokens that should not become the slug.
_TLD_TOKENS: frozenset[str] = frozenset(
    {"edu", "ac", "com", "net", "org", "gov", "au", "nz", "uk", "us", "ca"}
)

# Generic subdomain prefixes that do NOT represent an institution name.
# These are stripped before picking the slug token so that e.g.
# ``study.csu.edu.au`` → ``csu`` and ``courses.hud.ac.uk`` → ``hud``.
_GENERIC_SUBDOMAINS: frozenset[str] = frozenset({
    "www", "study", "international", "courses", "handbook",
    "programs", "programsandcourses", "apply", "admissions",
    "portal", "student", "students", "my", "secure", "web",
    "info", "find", "explore", "future", "search",
})

# Keys injected by auto_config_generator that are metadata, not config fields.
# Strip these before merging into UniConfig to avoid Pydantic validation errors.
_AUTO_CONFIG_META_KEYS: frozenset[str] = frozenset(
    {"_auto_generated", "_strategy", "_probe_summary", "_api_provider",
     "_api_endpoint_hint", "_blocked", "_notes"}
)


def _hostname_to_slug(hostname: str) -> str:
    """Derive a short slug from a hostname.

    Strips leading generic subdomain prefixes (www, study, international, …)
    then returns the first label that is not a TLD token.

    >>> _hostname_to_slug("www.acu.edu.au")
    'acu'
    >>> _hostname_to_slug("www.aut.ac.nz")
    'aut'
    >>> _hostname_to_slug("bond.edu.au")
    'bond'
    >>> _hostname_to_slug("www.uow.edu.au")
    'uow'
    >>> _hostname_to_slug("study.csu.edu.au")
    'csu'
    >>> _hostname_to_slug("courses.hud.ac.uk")
    'hud'
    >>> _hostname_to_slug("international.uts.edu.au")
    'uts'
    """
    parts = hostname.lower().split(".")
    # Strip leading generic subdomain labels (keep at least 2 parts).
    while len(parts) > 2 and parts[0] in _GENERIC_SUBDOMAINS:
        parts = parts[1:]
    for part in parts:
        if part not in _TLD_TOKENS:
            return part
    return parts[0]


def _infer_currency(hostname: str) -> str:
    """Return the most likely fee currency for a university hostname.

    Reads the TLD→currency map from ``scraper_config/defaults.yaml``
    (``currency_detection.tld_currency_map``) via ``currency_utils``.
    Falls back to ``currency_detection.default_currency`` from the same file.
    No hardcoded TLD list — extend the map in defaults.yaml to add new TLDs.
    """
    from app.services.scraper.currency_utils import infer_currency as _ic
    return _ic(hostname)


